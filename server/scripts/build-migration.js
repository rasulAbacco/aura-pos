#!/usr/bin/env node
/**
 * Emits a Prisma-convention migration.sql from the full DMMF.
 *
 * WHY THIS EXISTS: Prisma's native schema engine binary is downloaded from
 * binaries.prisma.sh, which was unreachable in the build sandbox. On any normal
 * machine use the standard workflow instead:
 *     npx prisma migrate dev --name <change>
 * and verify the committed init migration with:
 *     npx prisma migrate diff --from-migrations prisma/migrations --to-schema prisma/schema.prisma --script
 * which should print an empty migration (only the hand-written extras differ).
 *
 * Usage: node scripts/build-migration.js <dmmf.json> <out.sql> [extras.sql]
 */
import fs from 'node:fs';

const [, , dmmfPath, outPath, extrasPath] = process.argv;
const dm = JSON.parse(fs.readFileSync(dmmfPath, 'utf8'));
const q = (s) => `"${s}"`;
const out = [];

for (const e of dm.enums) {
  out.push(`-- CreateEnum\nCREATE TYPE ${q(e.name)} AS ENUM (${e.values.map((v) => `'${v.name}'`).join(', ')});\n`);
}

function colType(f) {
  let t;
  if (f.kind === 'enum') t = q(f.type);
  else {
    const nt = f.nativeType;
    switch (f.type) {
      case 'String': t = nt?.[0] === 'Uuid' ? 'UUID' : 'TEXT'; break;
      case 'Int': t = 'INTEGER'; break;
      case 'Boolean': t = 'BOOLEAN'; break;
      case 'DateTime': t = nt?.[0] === 'Date' ? 'DATE' : 'TIMESTAMP(3)'; break;
      case 'Decimal': t = nt ? `DECIMAL(${nt[1][0]},${nt[1][1]})` : 'DECIMAL(65,30)'; break;
      case 'Json': t = 'JSONB'; break;
      default: throw new Error(`Unmapped type ${f.type} on ${f.name}`);
    }
  }
  return f.isList ? `${t}[]` : t;
}

function colDefault(f) {
  if (!f.hasDefaultValue) return '';
  const d = f.default;
  if (d && typeof d === 'object' && !Array.isArray(d)) {
    if (d.name === 'now') return ' DEFAULT CURRENT_TIMESTAMP';
    if (d.name === 'uuid' || d.name === 'cuid') return ''; // generated by Prisma Client
    throw new Error(`Unsupported default fn ${d.name}`);
  }
  if (Array.isArray(d)) return ` DEFAULT ARRAY[${d.map((x) => `'${x}'`).join(',')}]::${colType({ ...f, isList: false })}[]`;
  if (typeof d === 'string') return f.kind === 'enum' ? ` DEFAULT '${d}'` : ` DEFAULT '${d.replace(/'/g, "''")}'`;
  return ` DEFAULT ${d}`;
}

const fks = [];
for (const m of dm.models) {
  const cols = [];
  for (const f of m.fields) {
    if (f.kind === 'object') {
      if (f.relationFromFields?.length) {
        const optional = !f.isRequired;
        const onDelete = f.relationOnDelete
          ? f.relationOnDelete.replace(/([a-z])([A-Z])/g, '$1 $2').toUpperCase()
          : optional ? 'SET NULL' : 'RESTRICT';
        fks.push(
          `-- AddForeignKey\nALTER TABLE ${q(m.name)} ADD CONSTRAINT ${q(`${m.name}_${f.relationFromFields.join('_')}_fkey`)} ` +
            `FOREIGN KEY (${f.relationFromFields.map(q).join(', ')}) REFERENCES ${q(f.type)}(${f.relationToFields.map(q).join(', ')}) ` +
            `ON DELETE ${onDelete} ON UPDATE CASCADE;\n`,
        );
      }
      continue;
    }
    const notNull = f.isRequired && !f.isList ? ' NOT NULL' : '';
    cols.push(`    ${q(f.name)} ${colType(f)}${notNull}${colDefault(f)}`);
  }
  const pk = m.fields.filter((f) => f.isId).map((f) => q(f.name));
  cols.push(`\n    CONSTRAINT ${q(`${m.name}_pkey`)} PRIMARY KEY (${pk.join(',')})`);
  out.push(`-- CreateTable\nCREATE TABLE ${q(m.name)} (\n${cols.join(',\n')}\n);\n`);
}

for (const idx of dm.indexes) {
  if (idx.type === 'id') continue;
  const fields = idx.fields.map((x) => x.name);
  const suffix = idx.type === 'unique' ? 'key' : 'idx';
  const name = idx.dbName || `${idx.model}_${fields.join('_')}_${suffix}`;
  out.push(
    `-- CreateIndex\nCREATE ${idx.type === 'unique' ? 'UNIQUE ' : ''}INDEX ${q(name)} ON ${q(idx.model)}(${fields.map(q).join(', ')});\n`,
  );
}

out.push(...fks);
if (extrasPath) out.push(`-- ───── Hand-written constraints (not expressible in Prisma schema) ─────\n${fs.readFileSync(extrasPath, 'utf8')}`);
fs.writeFileSync(outPath, out.join('\n'));
console.log(`wrote ${outPath}: ${dm.enums.length} enums, ${dm.models.length} tables, ${dm.indexes.length} indexes, ${fks.length} FKs`);

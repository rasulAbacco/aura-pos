/** Customer app request schemas (zod). */
import { z } from 'zod';

export const otpRequestSchema = z.object({ phone: z.string().trim().min(10).max(20) });
export const otpVerifySchema = z.object({ phone: z.string().trim().min(10).max(20), code: z.string().trim().regex(/^\d{6}$/, 'Enter the 6-digit code') });

export const SALON_CATEGORIES = ['SPA', 'MENS_SALON', 'SPA_SALON', 'UNISEX_SALON', 'WOMENS_PARLOUR'];

export const profileSchema = z.object({
  name: z.string().trim().min(2, 'Enter your name').max(60).optional(),
  email: z.union([z.literal(''), z.email()]).optional().transform((v) => (v === '' ? null : v)),
  gender: z.enum(['FEMALE', 'MALE', 'OTHER', '']).optional().transform((v) => (v === '' ? null : v)),
  birthday: z.union([z.literal(''), z.iso.date()]).optional().transform((v) => (v === '' ? null : v)),
});

export const salonsQuery = z.object({
  q: z.string().trim().max(60).optional(),
  category: z.enum(SALON_CATEGORIES).optional(),
  city: z.string().trim().max(60).optional(),
});

export const slotsQuery = z.object({
  branchId: z.uuid(),
  serviceIds: z.string().transform((s) => s.split(',').filter(Boolean)).pipe(z.array(z.uuid()).min(1).max(5)),
  date: z.iso.date(),
  staffId: z.uuid().optional(),
});

export const bookingSchema = z.object({
  requestId: z.uuid(), // generated by the app; sending the same request twice books once
  branchId: z.uuid(),
  serviceIds: z.array(z.uuid()).min(1).max(5),
  startsAt: z.coerce.date(),
  staffId: z.uuid().optional().nullable(),
  notes: z.string().trim().max(300).optional(),
});

export const orderSchema = z.object({
  requestId: z.uuid(),
  branchId: z.uuid(),
  items: z.array(z.object({ itemId: z.uuid(), quantity: z.coerce.number().int().min(1).max(20) })).min(1).max(20),
  notes: z.string().trim().max(300).optional(),
});

export const cancelSchema = z.object({ reason: z.string().trim().max(200).optional() });
